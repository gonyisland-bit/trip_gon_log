// Samples public/data/countries.geojson on a 2.5° grid and writes the land mask to src/data/worldDots.ts.
// Run: node scripts/build-world-dots.mjs
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const geo = JSON.parse(fs.readFileSync(path.join(root, 'public/data/countries.geojson'), 'utf8'));

const polys = [];
for (const f of geo.features) {
  const g = f.geometry;
  if (!g) continue;
  if (g.type === 'Polygon') polys.push(g.coordinates);
  else if (g.type === 'MultiPolygon') polys.push(...g.coordinates);
}
const boxes = polys.map(p => {
  let a = 1e9, b = -1e9, c = 1e9, d = -1e9;
  for (const [x, y] of p[0]) { a = Math.min(a, x); b = Math.max(b, x); c = Math.min(c, y); d = Math.max(d, y); }
  return [a, b, c, d];
});

function inRing(x, y, r) {
  let inside = false;
  for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
    const [xi, yi] = r[i], [xj, yj] = r[j];
    if ((yi > y) !== (yj > y) && x < (xj - xi) * (y - yi) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
function isLand(x, y) {
  for (let k = 0; k < polys.length; k++) {
    const b = boxes[k];
    if (x < b[0] || x > b[1] || y < b[2] || y > b[3]) continue;
    const p = polys[k];
    if (inRing(x, y, p[0]) && !p.slice(1).some(h => inRing(x, y, h))) return true;
  }
  return false;
}

const STEP = 2.5, TOP = 80, COLS = 360 / STEP, ROWS = Math.round(140 / STEP); // latitude 80°N .. 60°S
let bits = '';
for (let r = 0; r < ROWS; r++) {
  const lat = TOP - STEP / 2 - r * STEP;
  for (let c = 0; c < COLS; c++) bits += isLand(-180 + STEP / 2 + c * STEP, lat) ? '1' : '0';
}
const bytes = [];
for (let i = 0; i < bits.length; i += 8) bytes.push(parseInt(bits.slice(i, i + 8).padEnd(8, '0'), 2));
const b64 = Buffer.from(bytes).toString('base64');

const out = `// Generated by scripts/build-world-dots.mjs from public/data/countries.geojson. Do not edit by hand.
export const WORLD_DOTS = {
  cols: ${COLS},
  rows: ${ROWS},
  step: ${STEP},
  top: ${TOP},
  bits: '${b64}',
};

export interface WorldDot {
  lat: number;
  lng: number;
  /** Stable pseudo-random 0..1 used for staggering */
  h: number;
  /** Thinned by cos(lat) so a globe of these dots has even density */
  keep: boolean;
}

export function decodeWorldDots(): WorldDot[] {
  const { cols, rows, step, top, bits: packed } = WORLD_DOTS;
  const bin = atob(packed);
  const out: WorldDot[] = [];
  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < cols; c++) {
      const i = r * cols + c;
      if (!((bin.charCodeAt(i >> 3) >> (7 - (i & 7))) & 1)) continue;
      const lat = top - step / 2 - r * step;
      const h = Math.abs(Math.sin(i * 12.9898) * 43758.5453) % 1;
      out.push({ lat, lng: -180 + step / 2 + c * step, h, keep: h < Math.cos((lat * Math.PI) / 180) * 1.05 });
    }
  }
  return out;
}
`;
fs.writeFileSync(path.join(root, 'src/data/worldDots.ts'), out);
console.log(`worldDots.ts: ${bits.split('1').length - 1} land dots, ${b64.length} chars`);
